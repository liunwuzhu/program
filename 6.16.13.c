#include <stdio.h>
int main(void)
{
    int name[8];
    int i,m;
    for (i = 0;i < 8;i++)
    {
        name[i] = 1 << (i + 1);
    }
        m = 0;
    do
    {
        printf("%d\n",name[m]);
        m++;
    }
    while(m < 8);

    return 0;
}

/*`1 << k` 就是：**数字 1 的二进制，向左移动 k 位，右边补 0**

> 
> `<<` 叫**左移运算符**，不是小于号！

`1` 的二进制：`00000001`

- `1 << 1`：往左挪 1 位 → `00000010`  十进制 = **2** （\(2^1\)）
- `1 << 2`：往左挪 2 位 → `00000100`  十进制 = **4** （\(2^2\)）
- `1 << 3`：往左挪 3 位 → `00001000`  十进制 = **8** （\(2^3\)）
- `1 << 4`：往左挪 4 位 → `00010000`  十进制 = **16**（\(2^4\)）

✅ 规律：**`1 << k` = \(2^k\)**
*/