//参数传递就是“调用函数时，数据怎么从调用者（main）送到被调函数（printf）手里”。
//32 位老办法：把所有包裹（参数）全堆在一个公共货架（栈）上，被调函数按顺序去取。
//64 位新办法：给不同类型的包裹分配专用快递柜（寄存器），整数放整数柜，浮点数放浮点柜，速度飞快。
/*大白话重点：在 64 位 Windows 下，参数不再像火车车厢那样一串串连在一起，
而是像分拣中心的传送带——整数包裹走 1 号传送带（RCX），浮点包裹走 5 号传送带（XMM0）。
printf 拿着格式符（比如 %ld）去取件时，它只看 1 号传送带，根本不管 5 号传送带上有什么。 */ 
/*32 位程序是“人工排队取餐”（所有参数堆在栈里，一个个按顺序拿）。
64 位程序是“智能叫号系统”（整数去 A 窗口拿，浮点数去 B 窗口拿）。
你拿着“整数取餐码（%ld）”去 A 窗口，但你把“鸡腿（浮点数 3.0）”放到了 B 窗口。
A 窗口没人（残留 0），你就拿到了一个空盘子（打印 0）。
而你把“汉堡（整数 2000000000）”放到了 C 窗口，拿着正确的码（第 3 个 %ld）去取，就拿到了汉堡。*/